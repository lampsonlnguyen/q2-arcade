#!/usr/bin/env python3
"""Pack original 64px RGBA mark sprites into C, like Diamond Crush (Pillow)."""
from pathlib import Path
from PIL import Image, ImageDraw
root = Path(__file__).resolve().parents[1]
masks = []
for mark in ('cross', 'circle'):
    image = Image.new('L', (192, 192))
    draw = ImageDraw.Draw(image)
    if mark == 'cross':
        for x1, y1, x2, y2 in ((44,44,148,148),(148,44,44,148)):
            draw.line((x1,y1,x2,y2), fill=255, width=28)
            for x,y in ((x1,y1),(x2,y2)):
                draw.ellipse((x-14,y-14,x+14,y+14),fill=255)
    else:
        draw.ellipse((24,24,168,168), fill=255)
        draw.ellipse((52,52,140,140), fill=0)
    mask = image.resize((64,64), Image.Resampling.LANCZOS)
    rgba = Image.new('RGBA', (64,64), (114,219,247) if mark=='cross' else (255,204,102))
    rgba.putalpha(mask)
    rgba.save(root / 'assets/sprites' / (mark+'.png'))
    masks.append(list(mask.tobytes()))
with (root/'src/ttt_sprites.h').open('w') as f:
    f.write('/* SPDX-License-Identifier: GPL-3.0-or-later\n * Original sprites; generated by tools/make_ttt_sprites.py. */\n')
    f.write('static const unsigned char ttt_alpha[2][64*64]={\n')
    for mask in masks:
        f.write('{\n')
        for i in range(0,len(mask),64): f.write(','.join(map(str,mask[i:i+64]))+',\n')
        f.write('},\n')
    f.write('};\n')
